"""Sealed corrugated supply carton of the receiving preset (task open-carton).

What is built (labels as in params.py):
  * Regular slotted container (RSC), 14 x 10 x 8 in = 356 x 254 x 203 mm INSIDE (the FBA convention: box sizes are
    inside dimensions [S]); C-flute 32 ECT board, caliper 4 mm (C-flute 3.8-4.1 mm [V]); 0.55 kg/m2 [E]. The board is
    RIGID: corrugated board is not a thin sheet (its bending stiffness is ~1000x paper's and a 5 N fingertip load deflects
    a 127 mm flap by about a millimetre), and the contact world has ONE paper caliper per world, the
    thickest sheet stock's, so a 4 mm "sheet" could not be represented anyway.
  * Body: floor (two board layers: the closed bottom flaps), two long side walls and two end walls, one affine rigid body
    with a real cavity. Four top flaps: rigid 4 mm plates. Each is tied to the body at its score line by two stiff
    penalty pins on the hinge axis (the uncut board of the score: translation fixed, rotation about the score free) and
    loaded by the score's crease moment: an ipcworld.BodyHinge with params.FLAP_CREASE (the two-mechanism crease law fit
    to Nagasawa et al. 2019, moments scaled to 0.8 N m/m at 90 deg [E]). The hinge axis runs along the flap's
    mid-thickness at its outer edge, so a flap swings 0-180 deg without its board meeting the wall top (the real score
    crushes; the rigid model leaves a 50 um clearance instead [A]).
  * Majors (on the long walls) lie over the minors (on the end walls) and meet at the centre with a 3 mm seam gap
    (2-4 mm [E]). Nothing enforces the folding order except contact.
  * Crease state: the packer folds each flap from the flat blank to 90 deg at 0.2 rps (Nagasawa's test rate [A]) and the
    tape holds it closed for 24 h; the plastic set after that hold comes from integrating the crease law itself
    (aged_crease_state). The fit covers holds up to 20 s, so the 24 h value is an extrapolation of the logarithmic law
    [E]. It predicts a pop-up of 1-2 deg at release and ~4 deg after 10 s.
  * Seam tape: 3M 371 (params.BOPP_TAPE), 48 mm wide, centred on the seam over the full top, with 63 mm legs down both
    end panels (C-clip) [V tape, A legs]. The last 10 mm of the +x leg is a courtesy tab folded back on itself
    (adhesive to adhesive): a two-ply laminate of the tape (mass x2, membrane x2, bending x8, caliper x2 [D]) that is not
    stuck to the board [A]. Mesh 8 mm (64 x 7 vertices; TAPE_CELL).
  * Tape on board: every tape vertex lying on a board surface is bonded to that rigid body's material point through
    BodyBonds below (energy, gradient and Hessian in the contact world's implicit step) by the bilinear cohesive law of
    params.TAPE_ON_KRAFT (371 on kraft liner, release governed by liner delamination: Gamma 200 J/m2, interface stiffness
    1.5e10 Pa/m) with its strength regularized to the tape mesh (tape_law: 2 Gamma / h = 0.05 MPa at 8 mm instead of 0.45
    MPa, so a 90-degree peel runs at Gamma w, see there). Damage is irreversible, updated after each converged step, Gamma per released
    area booked. The law has no wet-out, dwell or ageing: "laid with a wipe-down and aged 24 h" is
    represented only by the bonds being fully formed.
  * Contents: eight tea cartons 150 x 80 x 70 mm, 120 g (SBS folding cartons, two layers of four) and a glass jar
    85 x 110 mm, 450 g [E], rigid. The jar's loose kraft wrap is NOT built (see REPORT).

The start state is generated by settling the authored geometry under gravity in the contact world (contents onto the
floor, carton onto the table, flaps against the tape) and cached under .cache/gift_bags/start_states by a hash of the
generator and inputs; the scene rebuilds the same bodies, pins, hinges and bonds and loads the settled poses, plastic
hinge state and bond damage.
"""

