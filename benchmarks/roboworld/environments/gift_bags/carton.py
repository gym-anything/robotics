def settled(table_z, xy=(0., 0.), *, cache=None, log=print):
    """The sealed carton as it arrives: authored geometry settled under gravity on a stainless table for SETTLE_S in the
    contact world (contents onto the floor, carton onto the table, the aged flaps' springback against the tape bonds).
    Cached by a hash of the generator and inputs. Returns a CartonState with settled poses, hinge and bond state."""
    from . import startcache as SC
    origin = (xy[0], xy[1], table_z + GAP)
    st = authored(origin)
    _localise(st)
    path = SC.locate(f"sealed_carton_{_cache_key(table_z, xy)}.npz", cache)
    if path.is_file():
        d = np.load(path, allow_pickle=False)
        st.tape.x0 = d["tape_x"]
        for k, b in enumerate(st.bodies):
            b.p, b.R = d["body_p"][k], d["body_R"][k]
        for k, h in enumerate(st.hinges):
            h["theta_p"], h["theta_r"] = map(float, d["hinges"][k])
        st.bonds.update(D=d["bond_D"], dmax=d["bond_dmax"])
        st.geometry["start_state"] = dict(cached=str(path), **json.loads(str(d["info"])))
        return st
    import time as _t
    table = table_body(table_z, xy)
    from .config import Config
    w = W.IPCWorld([st.tape], [], [table] + st.bodies, mu_pairs=Pm.FRICTION, friction_strict=True, tol=Config.newton_tol,
                   newton_max=Config.newton_max)                   # the scene's solver settings
    bonds = install(w, st)
    dt = 4e-3
    t0 = _t.perf_counter()
    rows = []
    p0 = {b.name: w.body_pose(i)[0].copy() for i, b in enumerate(w.bodies) if b.kind == "dynamic"}
    for i in range(int(round(SETTLE_S/dt))):
        w.step(dt)
        if i % 25 == 0 or i == int(round(SETTLE_S/dt)) - 1:
            row = dict(t=round(w.time, 3), iters=w.stats["last_iters"], unconverged=w.stats["unconverged"],
                       ke=float(w.kinetic_energy()), bonds_intact=bonds.intact_fraction,
                       max_opening_um=float(1e6*bonds.openings(w).max()), flaps_deg=flap_angles(w))
            rows.append(row)
            if log:
                log(f"  carton settle {row}")
    st.tape.x0 = w.x_free()[w.sheet_slices[0]].copy()
    names = [b.name for b in w.bodies]
    for b in st.bodies:
        b.p, b.R = w.body_pose(names.index(b.name))
    for h in st.hinges:
        hb = w.carton_hinges[h["flap"]]
        h["theta_p"], h["theta_r"] = float(hb.theta_p), float(hb.theta_r)
    st.bonds.update(D=bonds.D.copy(), dmax=bonds.dmax.copy())
    moved = {n: float(1e3*np.linalg.norm(w.body_pose(names.index(n))[0] - p)) for n, p in p0.items()}
    info = dict(wall_s=_t.perf_counter() - t0, sim_s=w.time, unconverged=w.stats["unconverged"],
                newton_per_step=w.stats["newton"]/max(w.stats["steps"], 1), bonds_intact=bonds.intact_fraction,
                max_opening_um=float(1e6*bonds.openings(w).max()), settle_move_mm=moved,
                initial_min_distance=w.initial_min_distance, log=rows)
    np.savez(path, tape_x=st.tape.x0, body_p=np.array([b.p for b in st.bodies]), body_R=np.array([b.R for b in st.bodies]),
             hinges=np.array([(h["theta_p"], h["theta_r"]) for h in st.hinges]), bond_D=bonds.D, bond_dmax=bonds.dmax,
             info=json.dumps(info, default=float))
    st.geometry["start_state"] = dict(built=str(path), **info)
    return st


# ----------------------------------------------------------------------------- measurements (evaluator)
def flap_angles(ipc, q=None):
    """Opening angle of each top flap, degrees: 0 closed, 90 standing vertical (the flat blank), 180 folded flat outward;
    from the flap's inward direction relative to the carton body's frame (rigid poses only)."""
    names = [b.name for b in ipc.bodies]
    if "carton_body" not in names:
        return {}
    _, Rc = ipc.body_pose(names.index("carton_body"), q)
    up = Rc[:, 2]
    out = {}
    for name, s in flap_specs().items():
        _, Rf = ipc.body_pose(names.index(name), q)
        inward0 = np.asarray(s["inward"], float)
        u = Rf @ inward0                       # flaps are authored with the carton's orientation (R equal at authoring)
        inw = Rc @ inward0
        out[name] = round(math.degrees(math.atan2(float(u @ up), float(u @ inw))), 3)
    return out


def tape_status(ipc):
    """Seam tape state from the bonds: intact bonded area per body, and the fraction of the tape stations that joined
    the two majors at the start (bonded to both) where intact bonds to BOTH remain."""
    bonds = getattr(ipc, "carton_bonds", None)
    if bonds is None:
        return {}
    names = [b.name for b in ipc.bodies]
    bi = {n: names.index(n) for n in ["carton_body", *FLAPS]}
    intact = bonds.D < 1.
    out = {f"bonded_area_{n}_cm2": 1e4*float(bonds.area[intact & (bonds.body == i)].sum()) for n, i in bi.items()}
    out["bonded_area_total_cm2"] = 1e4*float(bonds.area[intact].sum())
    out["bonded_area_start_cm2"] = 1e4*float(bonds.area.sum())
    # Stations along the tape (rows of its net) that were bonded to both majors at the start: the seam over the top and
    # the rows on the majors' end faces. A station still joins the majors if intact bonds to both remain there.
    ma, mb = bonds.body == bi["flap_major_yneg"], bonds.body == bi["flap_major_ypos"]
    rows = np.round(bonds.u/1e-6).astype(np.int64)
    both0 = np.intersect1d(rows[ma], rows[mb])
    still = np.intersect1d(rows[ma & intact], rows[mb & intact])
    out["seam_stations"] = int(len(both0))
    out["seam_joined_fraction"] = float(len(still)/max(len(both0), 1))
    out["tape_spans_majors"] = bool(len(still) > 0)
    out["bond_dissipated_j"] = float(bonds.dissipated)
    return out


