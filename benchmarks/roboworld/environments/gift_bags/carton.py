def draw(stage, path, body, mats):
    """A corrugated body as it is drawn: liner skins, cut edges and print as quads exactly on the faces of its boxes (so
    the 46 um tape lying one contact distance above stays visible), UVs counted in flutes, over the same boxes drawn
    0.3 mm undersize to close the hidden faces. Flutes run up the walls and from score to free edge on the flaps; an
    edge cut across the flutes shows the fluted medium."""
    from whiteboard.usd_scene import mesh as qmesh, bevel_box
    from pxr import Gf, UsdGeom, UsdShade
    r = body.render
    eps = 0.
    is_flap = "parts" not in r
    com = np.zeros(3) if is_flap else np.asarray(r["com_offset"], float)
    parts = [(r["half"], (0., 0., 0.))] if is_flap else r["parts"]
    flute = 2 if not is_flap else (1 if r["half"][0] > r["half"][1] else 0)     # axis the flutes run along
    E = np.eye(3)
    n_q = 0
    for j, (half, c) in enumerate(parts):
        half, c = np.asarray(half, float), np.asarray(c, float) - com
        g = bevel_box(stage, f"{path}/core_{j}", 2*half - 6e-4, 2e-4)
        UsdGeom.Xformable(g).AddTranslateOp().Set(Gf.Vec3d(*map(float, c)))
        UsdShade.MaterialBindingAPI.Apply(g.GetPrim()).Bind(mats["corrugated"])
        thin_ax = int(np.argmin(half))
        is_floor = not is_flap and thin_ax == 2
        for ax in range(3):
            for sgn in (-1., 1.):
                nrm = sgn*E[ax]
                edge = ax != thin_ax
                if not is_flap and ((edge and not (ax == 2 and sgn > 0)) or (is_floor and sgn < 0)):
                    continue                                          # hidden: wall ends and bottoms, the underside
                if edge:
                    long_ax = [i for i in range(3) if i not in (ax, thin_ax)][0]
                    u = E[long_ax]
                    v = np.cross(nrm, u)
                    nu = 2*half[long_ax]/_TILE
                    across = long_ax != flute
                    uv = [[0, 0], [nu, 0], [nu, 1], [0, 1]] if across else [[0, .02], [nu, .02], [nu, .1], [0, .1]]
                    mat = "carton_edge" if across else "carton_face"
                    hu, hv = half[long_ax], half[thin_ax]
                else:
                    v_ax = flute if flute != ax else 1
                    u_ax = [i for i in range(3) if i not in (ax, v_ax)][0]
                    v = E[v_ax]
                    u = np.cross(v, nrm)
                    hu, hv = half[u_ax], half[v_ax]
                    if not is_flap and ax == 1 and half[0] > .1 and sgn*c[1] > 0:     # outside of a long side panel
                        uv, mat = [[0, 0], [1, 0], [1, 1], [0, 1]], "carton_print"
                    else:
                        uv, mat = [[0, 0], [2*hu/_TILE, 0], [2*hu/_TILE, 2*hv/_TILE], [0, 2*hv/_TILE]], "carton_face"
                o_ = c + nrm*(half[ax] + eps)
                corners = [o_ - u*hu - v*hv, o_ + u*hu - v*hv, o_ + u*hu + v*hv, o_ - u*hu + v*hv]
                q = qmesh(stage, f"{path}/skin_{n_q}", np.asarray(corners), [np.array([0, 1, 2, 3])], np.asarray(uv, float))
                UsdShade.MaterialBindingAPI.Apply(q.GetPrim()).Bind(mats[mat])
                n_q += 1
