# ----------------------------------------------------------------------------- crease ageing
@functools.lru_cache(maxsize=None)
def aged_crease_state(law=Pm.FLAP_CREASE, rate=FOLD_RATE, hold=AGE_S):
    """Fold a score from the flat blank (0) to 90 deg at `rate`, hold `hold` seconds, with the crease law's implicit
    return mapping (ipcworld.crease_return, the world's own update). Returns (theta_p, theta_r) of the held fold, rad,
    and a short history (moment per length vs hold time). Beyond the fitted 20 s holds this is an extrapolation [E]."""
    th, tp, tr = 0., 0., 0.
    dt = 4e-3
    for i in range(int(math.ceil(.5*math.pi/rate/dt))):
        th = min(.5*math.pi, rate*(i + 1)*dt)
        s1, s2 = W.crease_return(law, th - tp, tr, dt)
        tp += s1 + s2; tr += s2
    hist = [(0., law.k*(th - tp))]
    t, dt = 0., 1e-3
    marks = [1., 10., 100., 3600., hold]
    while t < hold - 1e-9:
        dt = min(dt*1.05, hold - t)
        s1, s2 = W.crease_return(law, th - tp, tr, dt)
        tp += s1 + s2; tr += s2; t += dt
        if marks and t >= marks[0] - 1e-9:
            hist.append((marks.pop(0), law.k*(th - tp)))
    return tp, tr, tuple(hist)


# ----------------------------------------------------------------------------- tape-to-body cohesive bonds
class BodyBonds:
    """Pressure-sensitive tape on a rigid (affine) body: each bonded tape vertex v is tied to a material point of body b
    (its own authored position in b's frame, r: one contact rest distance off the board surface) by the bilinear
    traction-separation law `law` (ipcworld.CohesiveLaw, per unit area, the vertex's tributary area a):
        delta = x_v - (A_b r + p_b),   E = 1/2 (1 - D) k a |delta|^2
    D grows irreversibly with the largest opening dmax (linear softening from delta0 = sigma/k to deltaf = 2 Gamma/
    sigma); the energy dissipated so far, Gamma a (dmax - delta0)/(deltaf - delta0), is booked in `dissipated` (Gamma a
    for a fully opened bond). Mixed mode is isotropic in |delta|, as in ipcworld.Bonds (sheet to sheet). The scene uses tape_law(): params.TAPE_ON_KRAFT with its strength regularized to
    the tape mesh (see there). Registered in ipc.bonds so checkpoints carry D/dmax/dissipated (get_state/set_state copy
    exactly those attributes plus `n`, kept zero); `tri` is empty so the tear code's per-triangle bond queries skip it."""

    def __init__(self, vi, body, r, area, law, names=None):
        self.vi = np.asarray(vi, np.int64)
        self.body = np.asarray(body, np.int64)
        self.r = np.asarray(r, float).reshape(-1, 3)
        self.area = np.asarray(area, float)
        self.law = law
        self.names = names or {}
        self.D = np.zeros(len(self.vi))
        self.dmax = np.zeros(len(self.vi))
        self.n = np.zeros((len(self.vi), 3))
        self.tri = np.zeros(0, np.int64)
        self.dissipated = 0.

    def anchors(self, w, q):
        """World anchor positions (B,3) and each bond's affine DOF offset (-1: static body)."""
        X = np.zeros((len(self.vi), 3))
        off = np.full(len(self.vi), -1, np.int64)
        for b in np.unique(self.body):
            m = self.body == b
            bd = w.bodies[b]
            if bd.kind == "static":
                X[m] = self.r[m] @ bd.R.T + bd.p
            else:
                o = w.body_dof[b]
                A = q[o+3:o+12].reshape(3, 3)
                X[m] = self.r[m] @ A.T + q[o:o+3]
                off[m] = o
        return X, off

    def _env(self, s_):
        """Traction (Pa) on the monotonic-loading envelope at opening s_."""
        d0, df = self.law.delta0, self.law.deltaf
        return np.where(s_ <= d0, self.law.k*s_, np.where(s_ >= df, 0., self.law.sigma*(df - s_)/(df - d0)))

    def _psi(self, s_):
        """Work per area of opening monotonically to s_ (the envelope's integral; Gamma at s_ >= deltaf)."""
        d0, df, sg = self.law.delta0, self.law.deltaf, self.law.sigma
        soft = .5*sg*d0 + sg*(df*(s_ - d0) - .5*(s_*s_ - d0*d0))/(df - d0)
        return np.where(s_ <= d0, .5*self.law.k*s_*s_, np.where(s_ >= df, self.law.Gamma, soft))

    def term(self, w, q, xc_prev, dt, want):
        """Cohesive potential with the damage implicit in the step: up to the largest opening reached before (dmax, and
        at least delta0) a bond is the secant spring through its envelope point; beyond it the energy follows the
        envelope itself, so within a step the traction never exceeds the law. (With the damage frozen during a step and
        updated after it, the stiff undamaged spring overshot the 19 N row peak to 36-39 N for several steps and a
        90-degree peel averaged 1.35 x Gamma w.) The
        softening branch has negative radial curvature; the Newton matrix keeps its positive part (tangential T/delta),
        the line search guards the energy."""
        g = np.zeros(w.n_dof)
        coo = ([], [], [])
        live = self.D < 1.
        if not live.any():
            return 0., g, coo
        vi, r, a_ = self.vi[live], self.r[live], self.area[live]
        X, off = self.anchors(w, q)
        X, off = X[live], off[live]
        x = q[:3*w.n_free].reshape(-1, 3)[vi]
        d = x - X
        dn = np.linalg.norm(d, axis=1)
        d0 = self.law.delta0
        m = np.maximum(self.dmax[live], d0)                        # history point on the envelope
        ks = self._env(m)/m                                        # secant stiffness per area (k while undamaged)
        beyond = dn > m
        E = float((a_*np.where(beyond, .5*ks*m*m + self._psi(dn) - self._psi(m), .5*ks*dn*dn)).sum())
        T = np.where(beyond, self._env(dn), ks*dn)                 # traction magnitude (Pa)
        dhat = d/np.maximum(dn, 1e-30)[:, None]
        f = (a_*T)[:, None]*dhat
        np.add.at(g, (3*vi[:, None] + np.arange(3)).ravel(), f.ravel())
        dyn = off >= 0
        if dyn.any():
            o, fd, rd = off[dyn], f[dyn], r[dyn]
            for c in range(3):
                np.add.at(g, o + c, -fd[:, c])
                for j in range(3):
                    np.add.at(g, o + 3 + 3*c + j, -fd[:, c]*rd[:, j])
        if want:
            # per-bond 3x3 stiffness: secant branch ks I; envelope branch (T/delta)(I - d d^T) (+ radial slope if > 0)
            kt = a_*np.where(beyond, T/np.maximum(dn, 1e-30), ks)
            kr = a_*np.where(beyond, np.where(dn <= d0, self.law.k, 0.), ks)
            K = kt[:, None, None]*np.eye(3) + (kr - kt)[:, None, None]*dhat[:, :, None]*dhat[:, None, :]
            st = ~dyn
            if st.any():
                i3 = 3*vi[st][:, None] + np.arange(3)
                coo[0].append(np.repeat(i3[:, :, None], 3, 2).ravel()); coo[1].append(np.repeat(i3[:, None, :], 3, 1).ravel())
                coo[2].append(K[st].ravel())
            if dyn.any():
                o, rd, n_ = off[dyn], r[dyn], int(dyn.sum())
                J = np.zeros((n_, 3, 15))
                idx = np.zeros((n_, 15), np.int64)
                for c in range(3):
                    J[:, c, c] = 1.; J[:, c, 3 + c] = -1.
                    idx[:, c], idx[:, 3 + c] = 3*vi[dyn] + c, o + c
                    for j in range(3):
                        J[:, c, 6 + 3*c + j] = -rd[:, j]
                        idx[:, 6 + 3*c + j] = o + 3 + 3*c + j
                H = np.einsum("bia,bij,bjc->bac", J, K[dyn], J)
                coo[0].append(np.repeat(idx[:, :, None], 15, 2).ravel()); coo[1].append(np.repeat(idx[:, None, :], 15, 1).ravel())
                coo[2].append(H.ravel())
        return E, g, coo

    def openings(self, w, q=None):
        q = w.q if q is None else q
        X, _ = self.anchors(w, q)
        return np.linalg.norm(w.x_free(q)[self.vi] - X, axis=1)

    def after(self, w, dt):
        op = np.where(self.D < 1., self.openings(w), 0.)
        d0, df = self.law.delta0, self.law.deltaf
        frac = lambda m_: np.clip((m_ - d0)/(df - d0), 0., 1.)       # dissipated / (Gamma a) at history opening m_
        new = np.maximum(self.dmax, op)
        self.dissipated += float((self.area*self.law.Gamma*(frac(new) - frac(self.dmax))).sum())
        self.dmax = new
        Dn = np.where(self.dmax <= d0, 0., np.where(self.dmax >= df, 1.,
                      df*(self.dmax - d0)/np.maximum(self.dmax*(df - d0), 1e-30)))
        self.D = np.maximum(self.D, np.clip(Dn, 0., 1.))

    def traction_force(self, w):
        """Bond force on each tape vertex (B,3), N (pulls the vertex back toward its anchor); state after a step."""
        X, _ = self.anchors(w, w.q)
        d = w.x_free()[self.vi] - X
        m = np.maximum(self.dmax, self.law.delta0)
        return -(self.area*(self._env(m)/m)*(self.D < 1.))[:, None]*d

    @property
    def intact_fraction(self):
        return float((self.D < 1.).mean()) if len(self.D) else 0.

    def intact_area(self, body=None):
        m = self.D < 1.
        if body is not None:
            m &= self.body == body
        return float(self.area[m].sum())


def tape_law(cell=TAPE_CELL, base=Pm.TAPE_ON_KRAFT):
    """params.TAPE_ON_KRAFT with its strength regularized to the tape mesh: sigma = 2 Gamma / h, Gamma and k unchanged.

    Why: the bonds are lumped per tape vertex, so the peel front advances one row of width w and spacing h at a time. With
    the measured liner strength (0.45 MPa) a row must be pulled to sigma w h ~ 86 N before it softens, and once it lets go
    (after opening deltaf = 0.89 mm) the inextensible peeled arm goes slack until the pull has travelled h(1 - cos theta):
    a 90-degree peel then averaged 71 N against Kendall's Gamma w = 9.6 N, the pull doing 7.4 x the booked fracture work.
    The real cohesive zone (~0.4 mm from the tape's bending
    stiffness, sigma and Gamma) is ten times smaller than the mesh. Lowering sigma to 2 Gamma / h makes a row open over
    deltaf = h, so in a 90-degree peel each row's Gamma w h of work is done over a pull travel of h: the mean force is
    Gamma w and the fracture energy per area exactly Gamma. Equivalently the row's softening slope
    sigma^2 w h / (2 Gamma) stays below the peeled arm's stiffness E t w / L (no snap) for arms up to
    L = 2 Gamma E t / (h sigma^2) = E t h / (2 Gamma): 1.2 m at 8 mm, longer than this tape. The force is a sawtooth: each
    row peaks at sigma w h = 2 Gamma w (19.2 N) and falls to zero over h, a stick-slip of the lumped bonds, not of the
    adhesive. This is the standard
    engineering treatment of cohesive zones on coarse meshes (Turon, Davila, Camanho & Costa, "An engineering solution
    for mesh size effects in the simulation of delamination using cohesive zone models", Eng. Fract. Mech. 74 (2007),
    doi 10.1016/j.engfracmech.2006.08.025; the rule sigma = 2 Gamma / h here is derived above, not taken from it).
    What it changes: a bonded row stretches up to h (8 mm) before it lets go instead of 0.9 mm, and a straight pull on
    a bonded patch with no edge to peel from fails at 2 Gamma / h = 50 kPa instead of 450 kPa.
    LIMIT (measured): the law is right for a peel NORMAL to the board only. Pulled back along itself (180 deg) the lumped
    front row is loaded in shear, shares the load with the rows behind it through the tape's membrane, and lets go in
    bursts: 18.7 N mean with 100 N peaks against Kendall's Gamma w / 2 = 4.8 N, the pull doing 3.4 x the booked work.
    A real 180-degree peel folds the tape on a small radius and
    opens the adhesive in peel at the fold; a tape vertex per 4 mm on a rigid board has no such fold. Low-angle pulls
    (toward lap shear) are likewise not validated. The assisted run therefore peels at 90 degrees throughout."""
    return W.CohesiveLaw(f"{base.name}, strength regularized to the {cell*1e3:g} mm tape mesh (sigma = 2 Gamma / h)",
                         k=base.k, Gamma=base.Gamma, sigma=2.*base.Gamma/cell)


def install_body_bonds(ipc, bonds):
    ipc.bonds.append(bonds)
    ipc.extra_terms = list(getattr(ipc, "extra_terms", [])) + [bonds.term]
    ipc.post_terms = list(getattr(ipc, "post_terms", [])) + [bonds.after]
    return bonds


# ----------------------------------------------------------------------------- authored carton
def _box_dist(P, half, centre):
    d = np.abs(P - np.asarray(centre)) - np.asarray(half)
    return np.linalg.norm(np.maximum(d, 0.), axis=1) + np.minimum(d.max(1), 0.)


def caliper():
    """Contact caliper of the receiving world: its thickest sheet stock is the two-ply tab."""
    return W.contact_caliper(TAB_MAT)


def tape_net():
    """Rest net of the seam tape: u along the strip from the tab end (+x leg bottom), v across. Stations land exactly on
    the tab fold, both top edges and both leg ends. Returns X2, triangles, triangle material ids (1: tab), segments."""
    off = caliper()["rest_sheet_rigid"] + 5e-6
    l_top = L_OUT + 2*off                                  # the outer path over the two top edges
    nc = lambda length: max(1, int(round(length/TAPE_CELL)))
    seg = [(0., TAB, max(2, nc(TAB))), (TAB, LEG, nc(LEG - TAB)), (LEG, LEG + l_top, nc(l_top)),
           (LEG + l_top, 2*LEG + l_top, nc(LEG))]
    u = np.unique(np.concatenate([np.linspace(a, b, n + 1) for a, b, n in seg]))
    v = np.linspace(0., TAPE_W, int(round(TAPE_W/TAPE_CELL)) + 1)
    U, V = np.meshgrid(u, v, indexing="ij")
    X2 = np.stack([U.ravel(), V.ravel()], 1)
    nu, nv = len(u), len(v)
    idx = np.arange(nu*nv).reshape(nu, nv)
    T, tm = [], []
    for i in range(nu - 1):
        for j in range(nv - 1):
            a, b, c, d = idx[i, j], idx[i+1, j], idx[i+1, j+1], idx[i, j+1]
            T += [(a, b, c), (a, c, d)] if (i + j) % 2 == 0 else [(a, b, d), (b, c, d)]
            tm += [int(u[i + 1] <= TAB + 1e-9)]*2
    return X2, np.asarray(T, np.int64), np.asarray(tm), dict(off=off, l_top=l_top, u=u, v=v)


def tape_place(X2, info):
    """Carton-local 3D position of net points: +x leg (up the +x end face), top (along -x), -x leg (down)."""
    u, v = X2[:, 0], X2[:, 1]
    off, lt = info["off"], info["l_top"]
    y = v - TAPE_W/2
    x = np.where(u <= LEG, L_OUT/2 + off, np.where(u <= LEG + lt, L_OUT/2 + off - (u - LEG), -L_OUT/2 - off))
    z = np.where(u <= LEG, Z_TOP + off - (LEG - u), np.where(u <= LEG + lt, Z_TOP + off, Z_TOP + off - (u - LEG - lt)))
    return np.c_[x, y, z]


@dataclass
class CartonState:
    bodies: list                     # [carton body, 4 flaps, 8 tea, jar] (contact-world Bodies)
    tape: object                     # W.Sheet
    pins: list                       # (flap name, carton-local point, flap-local point)
    hinges: list                     # dicts: flap, pts (local), length, theta_p, theta_r
    bonds: dict                      # vi (tape-local), body name, r (body-local), area
    geometry: dict = field(default_factory=dict)
    crease: object = Pm.FLAP_CREASE  # score-line law (crease_scaled() for the [E] moment's sensitivity)


def crease_scaled(moment_90):
    """params.FLAP_CREASE with every moment scaled so the fold moment at 90 deg (0.2 rps) is `moment_90` N m/m (0.8 in the
    ledger [E]; sensitivity range 0.3-2); angles and rates unchanged."""
    c, f = Pm.FLAP_CREASE, moment_90/.8
    return W.CreaseLaw(f"C-flute score line x{f:g}", k=c.k*f, m_a=c.m_a*f, omega0=c.omega0, k2=c.k2*f, m2=c.m2*f, omega2=c.omega2)


def authored(origin, crease=Pm.FLAP_CREASE):
    """Authored (unsettled) carton at `origin` (outer bottom centre, world): bodies, tape, pins, hinges, bond spec."""
    from .scene import box_body, prism_body
    from .giftbox import rigid_from_boxes
    o = np.asarray(origin, float)
    m = masses()
    body = rigid_from_boxes("carton_body", body_parts(), m["body"], o, mu=Pm.MU["carton"], material="corrugated", cell=.02,
                            half=(L_OUT/2, W_OUT/2, Z_SIDE/2))
    body.fmat = "corrugated"
    com_c = body.render["com_offset"]
    bodies = [body]
    specs = flap_specs()
    pins, hinges = [], []
    tp, tr, hist = aged_crease_state(crease)
    for name in FLAPS:
        s = specs[name]
        half, c = np.asarray(s["half"]), np.asarray(s["centre"])
        n = (max(2, int(round(2*half[0]/.03))), max(2, int(round(2*half[1]/.03))), 1)
        fb = box_body(name, tuple(half), o + c, m[s["kind"]], mu=Pm.MU["carton"], n=n, material="corrugated", fmat="corrugated")
        bodies.append(fb)
        a, b = (np.asarray(p) for p in s["axis"])
        for p in (a, b):
            pins.append((name, p - com_c, p - c))
        hinges.append(dict(flap=name, axis=(a, b), wall=np.asarray(s["wall"]), plate=(a + b)/2 + .05*np.asarray(s["inward"]),
                           length=s["length"], aged=(tp, tr)))
    for name, kind, c, dims in content_specs():
        if kind == "box":
            bodies.append(box_body(name, dims, o + np.asarray(c), TEA_MASS, mu=.4, n=(3, 4, 2), material="tea_carton", fmat="carton"))
        else:
            r_, h = dims
            ang = np.linspace(0., 2*np.pi, JAR_SIDES, endpoint=False)
            outline = np.c_[r_*np.cos(ang), r_*np.sin(ang)]
            jb = prism_body(name, outline, h, o + np.asarray(c), JAR_MASS, mu=.3, material="glass_jar", fmat="glass")
            jb.render["radius"], jb.render["height"] = r_, h
            bodies.append(jb)
    X2, T, tm, info = tape_net()
    x0 = tape_place(X2, info) + o
    tape = W.Sheet("seam_tape", X2, T, x0, [Pm.BOPP_TAPE, TAB_MAT], tm, md_angle=0.)
    tape.fmat = "packtape"
    tape.render = dict(kind="packing_tape")
    # bonds: each tape vertex outside the tab onto the nearest board surface within reach
    area = np.zeros(len(X2))
    e1, e2 = X2[T[:, 1]] - X2[T[:, 0]], X2[T[:, 2]] - X2[T[:, 0]]
    A = .5*np.abs(e1[:, 0]*e2[:, 1] - e1[:, 1]*e2[:, 0])
    np.add.at(area, T.ravel(), np.repeat(A/3, 3))
    P = x0 - o
    cand = {"carton_body": [(np.asarray(h), np.asarray(c)) for h, c in body_parts()]}
    for name in FLAPS:
        cand[name] = [(np.asarray(specs[name]["half"]), np.asarray(specs[name]["centre"]))]
    dist = np.stack([np.min([_box_dist(P, h, c) for h, c in parts], 0) for parts in cand.values()], 1)
    names = list(cand)
    best = dist.argmin(1)
    reach = 1.6*info["off"]
    ok = (X2[:, 0] >= TAB - 1e-9) & (dist.min(1) <= reach)
    centres = {b.name: b.p for b in bodies}
    bvi = np.flatnonzero(ok)
    normals = []                                   # outward board normal at each bond (authored with every R = I)
    for i in bvi:
        parts = list(cand.values())[best[i]]
        k = int(np.argmin([_box_dist(P[i:i+1], h, c)[0] for h, c in parts]))
        h, c = parts[k]
        d = P[i] - np.clip(P[i], c - h, c + h)
        normals.append(d/max(np.linalg.norm(d), 1e-12))
    bond = dict(vi=bvi, body=[names[best[i]] for i in bvi], area=area[bvi],
                r=np.array([x0[i] - centres[names[best[i]]] for i in bvi]), n=np.asarray(normals), u=X2[bvi, 0])
    geo = dict(L_in=L_IN, W_in=W_IN, D_in=D_IN, board_t=T_B, L_out=L_OUT, W_out=W_OUT, z_top=Z_TOP, z_side=Z_SIDE,
               z_end=Z_END, seam=SEAM, flap_depth=FLAP_D, masses=m, flaps={k: dict(kind=v["kind"], inward=v["inward"],
               axis=[list(map(float, p)) for p in v["axis"]], length=v["length"]) for k, v in specs.items()},
               tape=dict(width=TAPE_W, leg=LEG, tab=TAB, cell=TAPE_CELL, vertices=len(X2), bonded=len(bvi),
                         tab_vertices=int((X2[:, 0] <= TAB + 1e-9).sum())),
               aged_crease=dict(theta_p_deg=math.degrees(tp), theta_r_deg=math.degrees(tr),
                                moment_n_m_per_m_vs_hold_s=[list(h) for h in hist]),
               contents=list(CONTENTS))
    return CartonState(bodies, tape, pins, hinges, bond, geo, crease)


def install(ipc, st):
    """Scene ipc_setup hook: pins, crease hinges (aged or cached plastic state) and tape bonds on a built world. The
    sheet `seam_tape` and the bodies are found by name. Returns the BodyBonds."""
    bi = install_hinges(ipc, st)
    sl = ipc.sheet_slices[[s.name for s in ipc.sheets].index("seam_tape")]
    b = st.bonds
    bonds = BodyBonds(np.asarray(b["vi"]) + sl.start, [bi[n] for n in b["body"]], b["r"], b["area"], tape_law())
    bonds.u = np.asarray(b["u"], float)                    # station along the tape (net coordinate), for tape_status
    if "D" in b:
        bonds.D, bonds.dmax = np.asarray(b["D"], float).copy(), np.asarray(b["dmax"], float).copy()
    install_body_bonds(ipc, bonds)
    ipc.carton_bonds = bonds
    return bonds


def install_hinges(ipc, st):
    """The four flaps' score lines: two penalty pins each (PIN_K) and the crease hinge (params.FLAP_CREASE) with its
    plastic state. Returns {name: body index}."""
    names = [b.name for b in ipc.bodies]
    bi = {n: names.index(n) for n in ["carton_body", *FLAPS]}
    for flap, rc, rf in st.pins:                         # body-local points (authored with every R = I)
        ipc.pins.append(W.Pin(bi[flap], np.asarray(rf, float), bi["carton_body"], np.asarray(rc, float), PIN_K))
    ipc.carton_hinges = {}
    for h in st.hinges:
        f = h["flap"]
        loc = h["local"]
        hb = W.BodyHinge(pts=((bi["carton_body"], loc["a"]), (bi["carton_body"], loc["b"]), (bi["carton_body"], loc["wall"]),
                              (bi[f], loc["plate"])), length=h["length"], law=st.crease,
                         theta_p=h["theta_p"], theta_r=h["theta_r"])
        ipc.hinges_b.append(hb)
        ipc.carton_hinges[f] = hb
    ipc.carton_hinge_sign = {h["flap"]: h["sign"] for h in st.hinges}
    return bi


def _localise(st):
    """Body-local hinge/pin points from the authored carton-local geometry (call before any pose changes)."""
    by = {b.name: b for b in st.bodies}
    c = by["carton_body"]
    o = c.p - c.render["com_offset"]
    for h in st.hinges:
        f = by[h["flap"]]
        a, b_ = h["axis"]
        h["local"] = dict(a=a - c.render["com_offset"], b=b_ - c.render["com_offset"],
                          wall=h["wall"] - c.render["com_offset"], plate=o + h["plate"] - f.p)
        theta = W.hinge_angles(np.array([o + a, o + b_, o + h["wall"], o + h["plate"]]), np.array([[0, 1, 2, 3]]))[0][0]
        s = np.sign(theta) or 1.
        h["sign"] = float(s)
        tp, tr = h["aged"]
        h["theta_p"], h["theta_r"] = s*tp, s*tr
        h["closed_angle_deg"] = math.degrees(theta)


def _cache_key(table_z, xy):
    from . import scene as S, giftbox as GB, startcache as SC
    src = SC.code(W) + SC.code(inspect.getmodule(_cache_key)) + "".join(
        SC.code(f) for f in (S.box_body, S.prism_body, S.prism_mesh, S.furniture_body, GB.rigid_from_boxes,
                                       GB.boxes_mesh))
    src += repr((round(table_z, 9), tuple(map(float, xy)), Pm.BOPP_TAPE, Pm.TAPE_ON_KRAFT, Pm.FLAP_CREASE,
                 sorted((tuple(sorted(k)), v) for k, v in Pm.FRICTION.items()), Pm.MU))
    return hashlib.sha256(src.encode()).hexdigest()[:16]


